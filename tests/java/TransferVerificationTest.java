    private static void stopThenDisconnect() throws Exception {
        try (Fixture f=new Fixture()) {
            f.file("cancelled.bin",MB);
            AtomicBoolean once=new AtomicBoolean();
            f.send.verificationHook=p->{ if (once.compareAndSet(false,true)) { f.send.transfer.stopVerification(); f.send.transfer.cancel(); } };
            f.run(options(true),options(true),1);
            check(!f.sent && !f.received && f.send.stopped==0 && f.send.incomplete==1 && f.receive.stopped==0,
                    "Hard cancellation after soft stop claimed a reusable connection");
            check(f.send.summary.cancelled,"Hard cancellation flag was lost");
        }
    }
    private static void uninterruptibleHashOpenFailsConnection() throws Exception {
        try (Fixture f=new Fixture()) {
            f.file("slow-provider.bin",1024);
            f.sourceFs.slowOpenMillis=5700;
            f.sourceFs.beforeHashOpen=()->f.send.transfer.stopVerification();
            f.run(options(true),options(true),1);
            check(!f.sent && !f.received && f.send.stopped==0 && f.send.incomplete==1,
                    "Unstoppable hash provider was reported as a clean reusable stop");
            check(f.send.summary.failures.stream().anyMatch(s->s.contains("workers did not stop")),
                    "Worker termination failure was not explained");
            long until=System.nanoTime()+TimeUnit.SECONDS.toNanos(3);
            while (System.nanoTime()<until && Thread.getAllStackTraces().keySet().stream().anyMatch(t->t.isAlive() && t.getName().equals("HFX-SHA256")))
                Thread.sleep(10);
            check(f.sourceFs.openHashes.get()==0 && Thread.getAllStackTraces().keySet().stream().noneMatch(t->t.isAlive() && t.getName().equals("HFX-SHA256")),
                    "A handle returned after shutdown was leaked");
        }
    }
