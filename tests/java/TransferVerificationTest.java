    private static final class AuditFs extends JdkTransferFileAccess {
        final AtomicInteger sealed,openHashes=new AtomicInteger(),maxHashes=new AtomicInteger(),hashes=new AtomicInteger();
        final Set<String> reserved=ConcurrentHashMap.newKeySet();
        final Map<String,Integer> generations=new ConcurrentHashMap<>();
        final Map<String,String> paths=new ConcurrentHashMap<>();
        final AtomicInteger maxReserved=new AtomicInteger(),resets=new AtomicInteger(),checkpoints=new AtomicInteger();
        volatile int expectedSealed,delay,corruptGenerations;
        volatile boolean earlyHash,earlyRetry,hashIo;
        volatile Runnable hashHook;
        volatile Runnable beforeHashOpen;
        volatile int slowOpenMillis;
        volatile IntSupplier comparisons;
        AuditFs(AtomicInteger sealed) { this.sealed=sealed; }
        private Handle monitored(Handle handle) {
            if (sealed.get()<expectedSealed) earlyHash=true;
            hashes.incrementAndGet(); maxHashes.accumulateAndGet(openHashes.incrementAndGet(),Math::max);
            AtomicBoolean closed=new AtomicBoolean();
            return new Handle(new SlowRead(handle.channel,delay,hashHook),()-> {
                if (closed.compareAndSet(false,true)) {
                    try { handle.close(); } finally { openHashes.decrementAndGet(); }
                }
            });
        }
        @Override public Handle openRead(String path) throws IOException {
            if (Thread.currentThread().getName().equals("HFX-SHA256") && slowOpenMillis>0) {
                if (beforeHashOpen!=null) beforeHashOpen.run();
                long until=System.nanoTime()+TimeUnit.MILLISECONDS.toNanos(slowOpenMillis);
                // Models an uninterruptible filesystem/provider call returning a late handle.
                while (System.nanoTime()<until) {
                    try { Thread.sleep(10); } catch (InterruptedException ignored) { }
                }
            }
            Handle h=super.openRead(path);
            return Thread.currentThread().getName().equals("HFX-SHA256")?monitored(h):h;
        }
        @Override public synchronized Prepared prepare(String root,String relative,String identity,long size,long modified,String hash,TransferOptions o) throws IOException {
            Prepared p=super.prepare(root,relative,identity,size,modified,hash,o);
            paths.put(p.token,relative); return p;
        }
        @Override public synchronized void checkpoint(String token,long offset) throws IOException {
            super.checkpoint(token,offset); if (offset>0) checkpoints.incrementAndGet();
        }
        @Override public synchronized void seal(String token) throws IOException {
            int generation=generations.merge(token,1,Integer::sum);
            if (paths.get(token).equals("repair.bin") && generation<=corruptGenerations) {
                try (RandomAccessFile f=new RandomAccessFile(stagingPath(token),"rw")) {
                    int value=f.read(); f.seek(0); f.write(value^0x40);
                }
            }
            super.seal(token); sealed.incrementAndGet();
        }
        @Override public synchronized Handle openSealedRead(String token) throws IOException {
            if (hashIo && paths.get(token).equals("repair.bin")) throw new IOException("Synthetic verification permission denied");
            Handle handle=super.openSealedRead(token);
            reserved.add(token); maxReserved.accumulateAndGet(reserved.size(),Math::max);
            return monitored(handle);
        }
        @Override public synchronized void releaseVerification(String token) throws IOException {
            super.releaseVerification(token); reserved.remove(token);
        }
        @Override public synchronized void completeVerification(String token,String expected,String actual) throws IOException {
            super.completeVerification(token,expected,actual); reserved.remove(token);
        }
        @Override public synchronized void resetForRetry(String token) throws IOException {
            if (resets.get()==0 && comparisons!=null && comparisons.getAsInt()<expectedSealed) earlyRetry=true;
            super.resetForRetry(token); resets.incrementAndGet();
        }
        @Override public synchronized void endSession() throws IOException { try { super.endSession(); } finally { reserved.clear(); } }
    }
