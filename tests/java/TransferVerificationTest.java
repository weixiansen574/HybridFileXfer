    /** Parses outgoing bytes as a stream; corruption is independent of write call boundaries. */
    private static final class CorruptOneBlock implements ByteChannel {
        final ByteChannel delegate;
        final ByteBuffer header=ByteBuffer.allocate(24);
        int payload,blocks;
        boolean changed;
        CorruptOneBlock(ByteChannel delegate) { this.delegate=delegate; }
        public int write(ByteBuffer bytes) throws IOException {
            int start=bytes.position(),limit=bytes.limit(),flip=-1;
            // Headers are bounded separately so this wrapper also handles split writes correctly.
            if (payload==0) {
                int wanted=header.position()<4?4-header.position():(header.getInt(0)==10?24:8)-header.position();
                bytes.limit(start+Math.min(bytes.remaining(),wanted));
            } else {
                bytes.limit(start+Math.min(bytes.remaining(),payload));
                if (!changed) { flip=start; bytes.put(flip,(byte)(bytes.get(flip)^1)); }
            }
            int n;
            try { n=delegate.write(bytes); }
            finally { if (flip>=0) bytes.put(flip,(byte)(bytes.get(flip)^1)); bytes.limit(limit); }
            if (payload>0) { payload-=n; if (flip>=0 && n>0) changed=true; }
            else {
                ByteBuffer copied=bytes.duplicate(); copied.position(start); copied.limit(start+n); header.put(copied);
                if (header.position()>=4) {
                    int command=header.getInt(0),length=command==10?24:8;
                    if (header.position()==length) {
                        if (command==10) { payload=header.getInt(16); blocks++; }
                        else if (command!=11) throw new IOException("Unexpected synthetic frame");
                        header.clear();
                    }
                }
            }
            return n;
        }
        public int read(ByteBuffer b) throws IOException { return delegate.read(b); }
        public boolean isOpen() { return delegate.isOpen(); }
        public void close() throws IOException { delegate.close(); }
    }
